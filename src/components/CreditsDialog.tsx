import { credits } from "../lib/data";
import { CloseIcon } from "./Icons";
import { Modal } from "./Modal";

export function CreditsDialog({ onClose }: { onClose: () => void }) {
  return (
    <Modal onClose={onClose} className="credits" labelledBy="credits-title" variant="pop">
      <div className="credits-card">
        <button type="button" className="credits-close" onClick={onClose} aria-label="Close photo credits">
          <CloseIcon />
        </button>
        <h2 id="credits-title" className="display">
          Photo credits
        </h2>
        <p className="credits-intro">With thanks to the photographers who shared these places.</p>
        <ul className="credits-list">
          {credits.map((c) => (
            <li key={c.id}>
              <span className="credits-id">{c.id.replace(/-/g, " ")}</span>
              <span className="credits-who">
                {c.sourceUrl ? (
                  <a href={c.sourceUrl} target="_blank" rel="noreferrer">
                    {c.author}
                  </a>
                ) : (
                  c.author
                )}
                {" · "}
                {c.licenseUrl ? (
                  <a href={c.licenseUrl} target="_blank" rel="noreferrer">
                    {c.license}
                  </a>
                ) : (
                  c.license
                )}
              </span>
            </li>
          ))}
          {credits.length === 0 && <li>Credits are generated by npm run photos.</li>}
        </ul>
      </div>
    </Modal>
  );
}
